export const LINGUAS = [
  ['pt', 'Português (Portugal)'],
  ['pt-BR', 'Português (Brasil)'],
  ['en', 'English'],
  ['es', 'Español'],
  ['fr', 'Français'],
  ['de', 'Deutsch'],
  ['zh', '中文'],
];
const CODES = LINGUAS.map(([c]) => c);
export const linguaValida = (l) => CODES.includes(l);

// Língua do aparelho (browser, telemóvel, Chromecast), ou português.
export function detectarLingua() {
  for (const raw of [...(navigator.languages || []), navigator.language]) {
    const l = String(raw || '').toLowerCase();
    if (l === 'pt-br') return 'pt-BR';
    const base = l.split('-')[0];
    if (CODES.includes(base)) return base;
  }
  return 'pt';
}

