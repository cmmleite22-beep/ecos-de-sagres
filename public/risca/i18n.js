// tr('pt', 'tv.round', { a: 1, b: 3 }) → 'Volta 1 de 3'
export function tr(lang, key, vars) {
  let s = TXT[lang]?.[key] ?? TXT.pt[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}
export const nomeLingua = (lang) => LINGUAS.find(([c]) => c === lang)?.[1] || lang;

// Traduz os elementos com data-i18n (texto), data-i18n-html (com <b>) e data-i18n-ph (placeholder).
export function traduzirPagina(lang, root = document) {
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = tr(lang, el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = tr(lang, el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = tr(lang, el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = tr(lang, el.dataset.i18nTitle);
  // os tipos de letra do jogo não têm caracteres chineses: carregar um que tenha
  if (lang === 'zh' && !document.getElementById('font-zh')) {
    const l = document.createElement('link');
    l.id = 'font-zh'; l.rel = 'stylesheet';
    l.href = 'https://fonts.googleapis.com/css2?family=ZCOOL+KuaiLe&display=swap';
    document.head.appendChild(l);
  }
  document.documentElement.classList.toggle('lang-zh', lang === 'zh');
}
